"""
ml/dataset.py

PyTorch Dataset for chord recognition training.

Supports two data sources:
  1. Synthetic dataset (generated by ml/generate_synthetic_dataset.py)
  2. Real annotated data (Isophonics/Billboard lab files + audio)

Each sample is a fixed-length chunk of log-CQT with per-frame chord labels.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import torch
from torch.utils.data import Dataset

from .chord_vocab import LABEL_TO_IDX, NUM_CLASSES
from .features import SR, HOP_LENGTH, extract_cnn_input, load_audio


class ChordDataset(Dataset):
    """
    Dataset for CRNN chord model training.

    Each item in the manifest is:
      {"audio": "path/to/file.wav", "labels": "path/to/labels.json"}

    Labels JSON format:
      [{"start": 0.0, "end": 2.5, "chord": "C:maj"}, ...]

    Args:
        manifest_path: Path to JSONL manifest file.
        chunk_frames: Number of frames per training chunk.
        augment: Whether to apply data augmentation.
    """

    def __init__(
        self,
        manifest_path: str | Path,
        chunk_frames: int = 200,
        augment: bool = True,
    ):
        self.manifest_path = Path(manifest_path)
        self.chunk_frames = chunk_frames
        self.augment = augment

        # Load manifest
        self.entries: list[dict] = []
        with open(self.manifest_path) as f:
            for line in f:
                line = line.strip()
                if line:
                    self.entries.append(json.loads(line))

        # Pre-compute features for all entries (small datasets fit in RAM)
        self.features: list[np.ndarray] = []  # (n_bins, n_frames) per entry
        self.labels: list[np.ndarray] = []    # (n_frames,) per entry, int class indices

        for entry in self.entries:
            audio_path = str(self.manifest_path.parent / entry["audio"])
            labels_path = str(self.manifest_path.parent / entry["labels"])

            # Extract log-CQT
            y, sr = load_audio(audio_path)
            log_cqt = extract_cnn_input(y, sr)  # (n_bins, n_frames)

            # Load and align chord labels
            with open(labels_path) as lf:
                chord_labels = json.loads(lf.read())

            n_frames = log_cqt.shape[1]
            frame_rate = sr / HOP_LENGTH
            label_indices = np.zeros(n_frames, dtype=np.int64)

            for seg in chord_labels:
                start_frame = int(round(seg["start"] * frame_rate))
                end_frame = int(round(seg["end"] * frame_rate))
                start_frame = max(0, min(start_frame, n_frames))
                end_frame = max(0, min(end_frame, n_frames))
                chord_label = seg["chord"]
                idx = LABEL_TO_IDX.get(chord_label, 0)  # fallback to N.C.
                label_indices[start_frame:end_frame] = idx

            self.features.append(log_cqt)
            self.labels.append(label_indices)

        # Build a list of (entry_idx, start_frame) for all valid chunks
        self.chunks: list[tuple[int, int]] = []
        for entry_idx, log_cqt in enumerate(self.features):
            n_frames = log_cqt.shape[1]
            if n_frames < self.chunk_frames:
                # Pad short entries
                self.chunks.append((entry_idx, 0))
            else:
                # Sliding window with 50% overlap
                stride = self.chunk_frames // 2
                for start in range(0, n_frames - self.chunk_frames + 1, stride):
                    self.chunks.append((entry_idx, start))

    def __len__(self) -> int:
        return len(self.chunks)

    def __getitem__(self, idx: int) -> tuple[torch.Tensor, torch.Tensor]:
        entry_idx, start = self.chunks[idx]
        log_cqt = self.features[entry_idx]
        label_seq = self.labels[entry_idx]

        n_bins, n_frames = log_cqt.shape
        end = start + self.chunk_frames

        # Extract or pad chunk
        if end <= n_frames:
            chunk = log_cqt[:, start:end]
            labels = label_seq[start:end]
        else:
            chunk = np.zeros((n_bins, self.chunk_frames), dtype=np.float32)
            labels_padded = np.zeros(self.chunk_frames, dtype=np.int64)
            avail = n_frames - start
            chunk[:, :avail] = log_cqt[:, start:]
            labels_padded[:avail] = label_seq[start:]
            chunk = chunk
            labels = labels_padded

        # Data augmentation
        if self.augment:
            # Pitch shift via circular shift of frequency bins (simulates transposition)
            if np.random.random() < 0.3:
                shift = np.random.randint(-3, 4) * 3  # shift by semitones (3 bins/semitone)
                chunk = np.roll(chunk, shift, axis=0)
                # Also shift labels to match transposition
                if shift != 0:
                    semitones = shift // 3
                    new_labels = np.zeros_like(labels)
                    for i in range(len(labels)):
                        old_idx = labels[i]
                        if old_idx == 0:  # N.C. stays N.C.
                            new_labels[i] = 0
                        else:
                            # Map class index to (root, quality), shift root, map back
                            quality_idx = (old_idx - 1) % 9
                            root_idx = (old_idx - 1) // 9
                            new_root = (root_idx + semitones) % 12
                            new_labels[i] = new_root * 9 + quality_idx + 1
                    labels = new_labels

            # Gaussian noise
            if np.random.random() < 0.2:
                chunk = chunk + np.random.randn(*chunk.shape).astype(np.float32) * 0.02

            # Time masking (SpecAugment-style)
            if np.random.random() < 0.2:
                mask_len = np.random.randint(1, min(10, self.chunk_frames // 4))
                mask_start = np.random.randint(0, self.chunk_frames - mask_len)
                chunk[:, mask_start:mask_start + mask_len] = 0.0

        # Shape: (1, n_bins, chunk_frames) for conv2d input
        x = torch.from_numpy(chunk[None, :, :].copy())
        y = torch.from_numpy(labels.copy())
        return x, y
